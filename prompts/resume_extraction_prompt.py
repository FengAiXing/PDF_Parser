"""
简历表提取提示词生成器
用于从简历表中提取人员姓名和业绩信息
"""

from typing import List


def extract_position_from_clause(clause_name: str) -> str:
    """
    从条款名称中提取职位信息
    
    Args:
        clause_name: 条款名称（如"拟派项目经理近年类似业绩"、"项目技术负责人业绩"、"监理工程师业绩要求"等）
        
    Returns:
        str: 职位名称（如"项目经理"、"技术负责人"、"监理工程师"等），如果无法提取则返回空字符串
    """
    # 职位关键词列表（按长度从长到短排序，优先匹配更具体的职位）
    position_keywords = [
        '总监理工程师', '专业监理工程师', '安全监理工程师', '监理工程师',
        '设计负责人', '施工负责人', '技术负责人', '安全负责人', '质量负责人',
        '项目负责人', '项目经理', '总工程师', '总监理', '工程师', '负责人'
    ]
    
    for keyword in position_keywords:
        if keyword in clause_name:
            return keyword
    
    return ""


def build_resume_extraction_prompt(
    performance_clauses: List[str],
    ranking: str = "第一名"
) -> str:
    """
    构建简历表人员姓名提取的提示词
    
    Args:
        performance_clauses: 包含"业绩"的条款列表
        ranking: 排名信息（如"第一名"、"第二名"等）
        
    Returns:
        str: 构建的提示词
    """
    # 格式化业绩条款
    clauses_text = "\n".join([f"- {clause}" for clause in performance_clauses])
    
    prompt = f"""你是一个专业的招投标文件分析专家。请从简历表中提取指定职位的人员姓名。

## 任务说明

根据以下业绩条款，从简历表中提取对应职位的人员姓名：

**业绩条款列表：**
{clauses_text}

## 核心提取要求

### 1. 严格按条款提取
- **只提取条款中明确提到的职位**：仔细分析每个业绩条款，识别其中明确提到的职位名称
- **不要提取条款中没有的职位**：即使简历表中存在其他职位，如果条款中没有提到，就不要提取
- **严格按照条款原文**：使用条款中的确切职位名称，不要修改或简化

### 2. 职位识别规则
- 仔细阅读每个业绩条款，找出其中明确提到的职位
- 常见职位关键词：
  - "项目经理"
  - "技术负责人" 
  - "施工负责人"
  - "设计负责人"
  - "安全负责人"
  - "项目负责人"
  - 其他在条款中明确提到的职位

### 3. 简历表分析
- 仔细分析简历表内容，识别人员配备表格
- 根据"拟在本项目任职"、"担任职务"、"岗位"等字段确定职位
- 提取对应职位的"姓名"字段
- 如果某个职位有多人，提取所有人员姓名，用逗号分隔
- 如果某个职位无人担任，对应字段留空

### 4. 变量名格式要求
- **严格按照"二第几名+条款原文+姓名"的格式生成变量名**
- 例如：条款是"拟派项目经理近年类似业绩" → 变量名："二{ranking}拟派项目经理近年类似业绩姓名"
- 例如：条款是"项目技术负责人业绩" → 变量名："二{ranking}项目技术负责人业绩姓名"
- **必须包含"二"前缀和排名信息（{ranking}）**
- **不要使用英文键名或简化名称**

## 输出格式

请按照以下JSON数组格式输出提取结果：

```json
[
  {{
    "variable_name": "二第几名+条款原文+姓名",
    "variable_value": "对应人员姓名",
    "reference_source": "简历表人员配备信息"
  }},
  {{
    "variable_name": "二第几名+另一个条款原文+姓名",   
    "variable_value": "对应人员姓名",
    "reference_source": "简历表人员配备信息"
  }}
]
```

## 输出要求

1. **变量名必须严格按照条款原文+姓名的格式**
2. **只输出条款中明确提到的职位对应的变量**
3. **如果某个职位在简历表中没有找到，不要输出对应的变量**
4. **确保每个变量名都包含完整的条款原文**
5. **变量值只包含人员姓名，不要包含其他信息**

## 注意事项

1. 仔细分析每个业绩条款，识别其中明确提到的职位
2. 严格按照条款原文生成变量名，不要修改或简化
3. 确保提取的姓名与职位正确对应
4. 只输出条款中明确提到的职位，不要输出其他职位
5. 如果条款中没有提到任何职位，返回空数组

请开始分析以下投标文件的内容，提取相关信息：

## 文件内容：
$content

请严格按照上述文件内容进行信息提取，不得编造或使用其他文档的信息。"""

    return prompt


def build_resume_performance_extraction_prompt(ranking: str, clause_name: str) -> str:
    """
    构建简历表业绩提取的提示词
    
    Args:
        ranking: 排名信息
        clause_name: 条款名称（完整条款，如"监理工程师业绩要求"）
        
    Returns:
        str: 构建的提示词
    """
    # 从条款名称中提取职位信息（仅用于判断，不在提示词中使用）
    position = extract_position_from_clause(clause_name)
    
    if not position:
        # 如果无法提取职位，使用通用提示词
        position_description = "指定职位"
    else:
        position_description = f"**{position}**职位"
    
    prompt = f"""你是一个专业的招投标文件分析专家。请从简历表的主要工作经历部分提取业绩表格。

## 任务要求

### 0. 重要：先查找人员配备汇总表，确定指定职位的第一人
**当前业绩条款：{clause_name}**

**关键要求（非常重要）：**
- **必须先查找人员配备汇总表（如"拟委任的主要人员汇总表"、"主要人员配备表"等）**
- **在人员配备汇总表中，找到与条款"{clause_name}"对应的职位人员**
- **根据条款名称中的职位关键词，在汇总表中查找包含该关键词的所有职位**
- **匹配规则：职位关键词匹配（不是完全匹配）**
  - **如果条款是"监理工程师业绩要求"，则汇总表中的"总监理工程师"、"专业监理工程师"、"安全监理工程师"、"监理工程师"都算匹配**
  - **如果条款是"项目经理业绩要求"，则汇总表中的"项目经理"、"副项目经理"等都算匹配**
  - **如果条款是"设计负责人业绩要求"，则汇总表中的"设计负责人"、"总设计负责人"等都算匹配**
- **选择规则（优先级从高到低）：**
  1. **优先选择汇总表中序号最小的（最靠前的）**
  2. **如果序号相同或接近，优先选择更具体的职位（如"总监理工程师"优先于"监理工程师"，"项目经理"优先于"副项目经理"）**
- **获取那个人的姓名**
- **然后只从那个人的简历表中提取业绩**
- **不要从其他职位人员的简历表中提取业绩**

### 1. 查找人员配备汇总表
- 在简历表内容中查找人员配备汇总表（通常标题包含"人员汇总表"、"人员配备表"、"主要人员"等）
- 汇总表通常包含以下列：序号、本项目任职（或"拟任职务"、"岗位"等）、姓名、职称、专业等
- **在汇总表中查找"本项目任职"（或"拟任职务"、"岗位"等）列，根据条款名称"{clause_name}"中的职位关键词，找到所有包含该关键词的职位行**
- **匹配示例：**
  - **条款："监理工程师业绩要求" → 匹配职位："总监理工程师"、"专业监理工程师"、"安全监理工程师"、"监理工程师"（都包含"监理工程师"关键词）**
  - **条款："项目经理业绩要求" → 匹配职位："项目经理"、"副项目经理"（都包含"项目经理"关键词）**
  - **条款："设计负责人业绩要求" → 匹配职位："设计负责人"、"总设计负责人"（都包含"设计负责人"关键词）**

### 2. 确定指定职位的第一人
- **如果汇总表中有多个匹配的职位人员，按照以下优先级选择：**
  1. **优先选择序号最小的（最靠前的）**
  2. **如果序号相同或接近，优先选择更具体的职位（如"总监理工程师"优先于"监理工程师"，"项目经理"优先于"副项目经理"）**
- **选择示例：**
  - **条款："监理工程师业绩要求"**
  - **汇总表中有：序号1的"总监理工程师"、序号2的"监理工程师"、序号5的"专业监理工程师"**
  - **应该选择：序号1的"总监理工程师"（因为序号最小，且职位名称更具体）**
- 获取那个人的姓名（从"姓名"列提取）
- **记录这个人的姓名和职位，后续只从这个人的简历表中提取业绩**

### 3. 定位指定人员的简历表
- 在简历表内容中查找对应姓名的简历表
- 识别方法：
  - 查找标题中包含该姓名的简历表（如"项目负责人简历表——XXX"、"XXX简历表"等）
  - 查找"姓名"字段为该姓名的简历表
  - **确认"拟在本项目任职"或"拟在本合同任职"字段包含条款"{clause_name}"中的职位关键词**
- **只处理这个人的简历表，忽略其他职位人员的简历表**

### 4. 定位主要工作经历表格
- 在指定人员的简历表中查找"主要工作经历"部分的表格
- 表格通常包含以下列：时间、类似业绩、担任职务、发包人及联系电话等
- 表格可能有跨页的情况，需要完整提取

### 5. 提取业绩表格
- 将主要工作经历表格中的每一行作为一个独立的业绩
- 每个业绩需要包含完整的表格结构（表头+单行数据）
- 使用HTML表格格式输出（table、tr、td标签）
- 变量名格式：{ranking}{clause_name}表1、{ranking}{clause_name}表2、{ranking}{clause_name}表3...（按顺序编号）

### 6. 表格格式要求
- 必须使用标准的HTML表格标签：<table>、<tr>、<td>
- 表格要有清晰的表头行（包含：时间、类似业绩、担任职务、发包人及联系电话等列）
- 每个业绩只包含一行数据行
- 保持原始数据的完整性和准确性

### 7. 提取规则
- **必须严格按照以下步骤执行：**
  1. 先查找人员配备汇总表
  2. 在汇总表中找到{position_description}的所有人员
  3. 选择序号最小的那一个（最靠前的）
  4. 获取那个人的姓名
  5. 只从那个人的简历表中提取业绩
- 仔细识别主要工作经历表格的表头，表头内容是不固定的，需要根据表格中的内容去准确识别
- 每一行数据代表一个业绩项目
- 如果表格跨页，需要完整提取所有行
- 确保每个业绩表格都包含表头和数据行

## 输出格式

请严格按照以下JSON格式输出：

```json
{{
  "performance_summary_table": {{
    "variable_name": "{ranking}{clause_name}汇总表",
    "table_content": "<table><tr><td>时间</td><td>类似业绩</td><td>担任职务</td><td>发包人及联系电话</td></tr><tr><td>...</td><td>...</td><td>...</td><td>...</td></tr></table>"
  }},
  "individual_performances": [
    {{
      "variable_name": "{ranking}{clause_name}表1",
      "table_content": "<table><tr><td>时间</td><td>类似业绩</td><td>担任职务</td><td>发包人及联系电话</td></tr><tr><td>2021年10月13日至2023年11月10日</td><td>阳信县第二高级中学改扩建工程</td><td>项目经理</td><td>阳信县第二高级中学 0543-8235088</td></tr></table>"
    }},
    {{
      "variable_name": "{ranking}{clause_name}表2",
      "table_content": "<table><tr><td>时间</td><td>类似业绩</td><td>担任职务</td><td>发包人及联系电话</td></tr><tr><td>2024年9月25日至2025年06月05日</td><td>鱼城国际冷链物流园建设项目</td><td>项目经理</td><td>济宁鱼城冷链物流产业发展有限公司</td></tr></table>"
    }}
  ]
}}
```

## 注意事项

1. **必须先查找人员配备汇总表，确定{position_description}的第一人（序号最小的）**
2. **只从那个人的简历表中提取业绩，不要从其他{position_description}的简历表中提取**
3. 只提取指定人员简历表中主要工作经历部分的表格，不要提取其他部分
4. 确保每个业绩表格都包含完整的表头行
5. 每个业绩表格只包含一行数据行
6. 保持原始数据的准确性，不要修改或简化
7. 如果找不到人员配备汇总表、找不到指定职位的第一人、或找不到该人员的简历表或主要工作经历表格，返回空的individual_performances数组

请开始分析以下简历表内容，提取业绩表格：

## 简历表内容：
$content

请严格按照上述内容进行提取，不得编造或使用其他文档的信息。"""

    return prompt

