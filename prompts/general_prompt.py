"""
通用条款提取提示词生成器（资格评审标准）
用于生成通用条款信息的AI提取提示词
"""

from typing import Dict, List, Any
from .prompt_utils import get_rank_name


def generate_general_prompt(
    candidate_count: int,
    clauses: List[str],
    other_requirements: str,
    candidate_names: Dict[int, str] = None,
    target_ranking: str = None
) -> str:
    """生成通用条款提取提示词
    
    Args:
        candidate_count: 候选人总数
        clauses: 条款列表
        other_requirements: 其他条款要求
        candidate_names: 候选人名称字典
        target_ranking: 目标排名（如"第一名"、"第二名"），如果提供，只提取该排名的信息
    """
    
    # 生成候选人名称说明
    candidate_names_text = ""
    if candidate_names:
        candidate_names_text = "\n**各候选人名称：**\n"
        for rank, name in candidate_names.items():
            rank_name = get_rank_name(rank)
            candidate_names_text += f"- {rank_name}：{name}\n"
    
    # 格式化条款
    clauses_text = "\n".join([f"- {clause}" for clause in clauses])
    
    # 生成变量名示例（使用第一个条款作为示例）
    example_clause = clauses[0] if clauses else "其他条款"
    
    # 如果指定了目标排名，只生成该排名的变量名示例
    if target_ranking:
        example_var_names = f"- {target_ranking}{example_clause}"
        target_ranking_instruction = f"\n**重要提示：当前处理的文件是{target_ranking}的投标文件，请只提取{target_ranking}的信息，不要提取其他排名的信息。**"
    else:
        example_var_names = "\n".join([
            f"- 第{i}名{example_clause}" for i in range(1, min(candidate_count + 1, 4))
        ])
        target_ranking_instruction = ""
    
    prompt = f"""## 一、角色定义
你是一位经验丰富的评标专家，负责提取和分析候选人投标文件中的各类信息。

## 二、任务说明
请仔细分析以下候选人投标文件内容，准确提取**资格评审标准中列出的条款信息**。
所有信息必须严格依据文件内容，不得自行编造或补充未提及内容。

## 三、文件类型特定指导
当前处理的文件类型：**candidate_bid_files（候选人投标文件）**

本次招标项目共有 {candidate_count} 名中标候选人。
{candidate_names_text}{target_ranking_instruction}

## 四、需要提取的条款信息

**⚠️ 重要说明：以下是需要提取的全部条款列表（已排除业绩和资质条款）**

**资格评审标准中的条款：**
{clauses_text}

**其他条款要求（作为判断依据）：**
{other_requirements if other_requirements else "未提供"}

**⚠️ 核心提取要求：**
1. **严格按照条款列表提取**：只提取上面列出的条款中明确要求的内容
2. **条款中没有提到的不要提取**：即使下面给出了提取规则（如项目经理、安全许可证等），如果条款列表中没有该项，就不要提取
3. **每个条款都要处理**：条款列表中的每个条款都要在投标文件中查找
4. **根据其他条款要求判断**：使用其他条款要求作为判断标准

## 五、提取规则

1. **准确性原则**
   - 所有信息必须来自原文，不得编造
   - 如实提取，保持原文表述
   - 如果信息不完整，请如实提取已有部分

2. **完整性原则**
   - 每个条款都要提取
   - 不要遗漏任何一个条款

3. **区分原则**
   - 请明确区分每个候选人的信息
   - 确保不要混淆不同候选人的信息

4. **判断原则**
   - 根据"其他条款要求"中的条件进行判断
   - 提取时需要包含足够的信息以便后续判断

## 六、条款提取格式参考

**⚠️ 重要：以下格式仅供参考，只有当条款列表中明确包含这些条款时才使用对应格式**

### 6.1 如果条款包含"项目经理"、"设计负责人"或"施工负责人"（单个职位或未用'、'分隔的职位）
**提取规则：**
1. 从其他条款要求这个变量中判断对该人员的要求是什么
2. 从投标文件第二部分 商务部分 第七章资格审查资料中查找该项对应信息
3. 按照以下格式提取：
```
职位名称：XXX
姓名：XXX
证书名称：XXX
证书编号：XXX
```

**注意：**
- 如果条款中包含多个职位且用'、'分隔（如"项目经理、设计负责人、施工负责人"），请使用专门的多职位提取规则（见下方6.1.1节）
- 如果条款只包含单个职位或职位未用'、'分隔，使用本格式

### 6.1.1 如果条款包含多个职位且用'、'分隔（如"项目经理、设计负责人、施工负责人"）
**⚠️ 重要：此类条款需要使用专门的多职位提取提示词，请参考多职位提取规则**

**提取规则：**
1. **条款中有哪些职位就要提取哪些，不能只提一个**
   - 如果条款是"项目经理、设计负责人、施工负责人"，必须提取这三个职位的信息
   - 不能只提取其中一个或两个职位

2. **每个职位占一个位置**
   - 除非是一个人兼职多个职位，否则每个职位都要单独提取
   - 如果条款中有3个职位，必须提取3个职位的信息

3. **兼任职位处理**
   - 如果一个人同时兼任多个职位，这一个人也算占了每一个兼任的职位
   - 例如：如果条款是"项目经理、设计负责人、施工负责人"，而某个人同时担任"项目经理"和"设计负责人"，那么：
     - 这个人占用了"项目经理"的位置
     - 这个人也占用了"设计负责人"的位置
     - 还需要另外一个人担任"施工负责人"

4. **优先提取规则**
   - 靠前的职位优先提取
   - 如果一个人兼任多个职位，优先提取靠前的职位组合

**提取格式：**
- **单个职位格式**：
```
职位名称：设计负责人
姓名：XXX
证书名称：XXX
证书编号：XXX
```

- **多个职位格式**（每个职位单独一段）：
```
职位名称：项目经理
姓名：XXX
证书名称：XXX
证书编号：XXX
职位名称：设计负责人
姓名：XXX
证书名称：XXX
证书编号：XXX
职位名称：施工负责人
姓名：XXX
证书名称：XXX
证书编号：XXX
```

- **一个人兼任多个职位格式**：
```
职位名称：项目经理、设计负责人
姓名：XXX
证书名称：XXX
证书编号：XXX
职位名称：施工负责人
姓名：XXX
证书名称：XXX
证书编号：XXX
```

### 6.2 如果条款包含"安全许可证"或"安全生产许可证"
**提取规则：**
1. 从其他条款要求这个变量中判断对投标人的该要求是什么
2. 根据其他条款要求中的要求，从文件中提取对应的满足条件的信息
3. 按照以下格式提取，如果有多个需要换行继续展示：
```
资质名称：XXX
资质编号：XXX
```

### 6.3 如果条款包含"营业执照"不要提取，这不属于资质相关信息，包括任何管理体系等认证也不属于资质相关信息

### 6.4 如果条款包含"联合体投标人"
**提取规则：**
1. 从投标文件中判断投标人是否为联合体投标人
2. 如果是联合体投标人，提取牵头人和所有成员信息
3. 如果是非联合体投标人，直接返回"非联合体投标人"

**提取格式：**
- **联合体投标人格式**：
```
牵头人：XXX
成员一：XXX
成员二：XXX
```
（如果有更多成员，继续添加"成员三："、"成员四："等）

- **非联合体投标人格式**：
```
非联合体投标人
```

**注意事项：**
- 必须准确判断投标人类型（联合体或非联合体）
- 如果是联合体，必须提取牵头人和所有成员，不要遗漏
- 成员按照"成员一"、"成员二"、"成员三"的顺序编号
- 每个成员信息单独一行，使用换行符（\n）分隔

### 6.5 其他条款
根据条款的具体要求提取相应信息：
- **财务状况**：提取财务报表相关数据
- **设备情况**：提取设备名称、型号、数量、购置时间等
- **人员配备**：提取人员姓名、职称、专业、证书等

**⚠️ 再次强调：只提取条款列表中明确要求的内容，条款中没有的不要提取**

## 七、输出格式

请严格按照JSON数组格式输出，每个变量是一个独立的对象：

```json
[
  {{
    "variable_name": "{target_ranking if target_ranking else '第一名'}{example_clause}",
    "variable_value": "资质名称：安全生产许可证\n资质编号：（晋）JZ安许证字[2023]XXXXXX号",
    "reference_source": {{
      "file_type": "candidate_bid_files",
      "page_number": "第X页",
      "section": "第二部分 商务部分 第七章资格审查资料",
      "content_preview": "...相关内容预览..."
    }}
  }}
]
```

**字段说明：**
- `variable_name`: 变量名称（由"候选人名次"+"条款名称"组成），例如条款名称为安全许可证，那么变量名称为'第一名安全许可证',如果条款名称为安全许可证资质，那么变量名称为'第一名安全许可证资质'变量名中的条款名称要与条款列表中的条款名称完全一致，不要简化和修改
- `variable_value`: 提取的变量值
- `reference_source`: 引用来源信息
  - `file_type`: 固定为 "candidate_bid_files"
  - `page_number`: 信息所在页码
  - `section`: 信息所在章节
  - `content_preview`: 相关内容预览（50-100字）

**注意事项：**
- **⚠️ 最重要**：严格按照条款列表提取，条款中没有的内容不要提取
- **项目经理、设计负责人、施工负责人**（仅当条款中有时）按照以下格式，如果有多个那么用换行符（\n）分隔：
  ```
  姓名：XXX
  证书名称：XXX
  证书编号：XXX
  ```
- **安全许可证**（仅当条款中有时）按照以下格式：
  ```
  资质名称：XXX
  资质编号：XXX
  ```
- 其他条款信息较多时，用分号（；）分隔各项内容
- 确保从投标文件第二部分 商务部分 第七章资格审查资料中查找
- 确保JSON格式正确，必须是数组格式
- **变量名必须与候选人排名对应**：{f'当前文件的变量以"{target_ranking}"开头（只提取当前文件对应的排名）' if target_ranking else '第一名的变量以"第一名"开头，第二名的变量以"第二名"开头'}

请开始分析以下投标文件的内容，提取相关信息：

## 文件内容：
$content
请严格按照上述文件内容进行信息提取，不得编造或使用其他文档的信息。
"""
    
    return prompt

