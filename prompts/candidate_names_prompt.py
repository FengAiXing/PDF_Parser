"""
候选人名称和得分提取提示词生成器
用于生成从评审结果和商务部分评分表中提取候选人名称和得分的AI提示词
"""


def generate_candidate_names_prompt(
    review_results: str, 
    count: int, 
    business_score_table: str = ""
) -> str:
    """
    生成提取候选人名称和得分的提示词
    
    Args:
        review_results: 评审结果内容（HTML表格）
        count: 需要提取的候选人数量
        business_score_table: 商务部分评分表内容（HTML表格）
        
    Returns:
        str: 生成的提示词
    """
    prompt = f"""
请从以下评审结果表格中，按照排名顺序提取前{count}名中标候选人的名称，并从商务部分评分表中提取这些候选人的所有评标条款得分。

评审结果表格：
{review_results}

商务部分评分表：
{business_score_table}

要求：
1. 按照排名顺序（从第1名到第{count}名）提取候选人名称
2. 提取完整的企业名称，包括公司类型后缀（如：有限公司、股份有限公司等）
3. **提取所有评标条款的得分**，不要遗漏任何条款
4. 对于每个评标条款，为每个候选人创建单独的变量

**变量命名规则（⚠️ 极其重要 - 必须严格遵守）：**

**核心原则：使用商务部分评分表中的条款名称，但必须去除分值范围（如【0~6】、【0~4】等）**

- **第一步：提取纯净的条款名称**
  - 商务部分评分表中的条款通常包含分值范围，例如：
    - "投标人近年类似业绩【0~6】"
    - "拟派项目经理近年类似业绩【0~4】"
    - "其他岗位主要人员配备情况【0~3.5】"
    - "三体系认证【0~1.5】"
  - **必须去除分值范围**（包括【】及其中的内容），只保留条款名称：
    - "投标人近年类似业绩【0~6】" → `投标人近年类似业绩`
    - "拟派项目经理近年类似业绩【0~4】" → `拟派项目经理近年类似业绩`
    - "其他岗位主要人员配备情况【0~3.5】" → `其他岗位主要人员配备情况`

- **第二步：构造变量名**
  - **一般条款**：变量名格式为 "分数+第几名+纯净条款名称"
  - **正确示例**：
    - 表格中是"投标人近年类似业绩【0~6】" → 变量名：`分数第一名投标人近年类似业绩` ✅
    - 表格中是"近年投标人类似项目业绩【0~6】" → 变量名：`分数第一名近年投标人类似项目业绩` ✅
    - 表格中是"业主反馈【0~5】" → 变量名：`分数第一名业主反馈` ✅
  - **错误示例**：
    - ❌ 变量名：`分数第一名投标人近年类似业绩【0~6】`（包含了分值范围）
    - ❌ 变量名：`分数第一名投标人业绩`（简化了条款名称）
    - ❌ 变量名：`分数第一名类似业绩`（省略了部分条款名称）

- **特殊处理：如果条款名称中包含"三体系认证"字段**：
  - 只保留"三体系认证"，去掉所有多余的描述或前后缀
  - 变量名格式为：分数+第几名+三体系认证
  - 例如：条款名称是"ISO三体系认证" → 变量名：分数第一名三体系认证
  - 例如：条款名称是"企业三体系认证情况" → 变量名：分数第一名三体系认证
  - 例如：条款名称是"三体系认证" → 变量名：分数第一名三体系认证

**变量命名步骤（详细）：**
1. 在商务部分评分表中找到条款（如："投标人近年类似业绩【0~6】"）
2. **去除分值范围**：删除【0~6】部分 → 得到：`投标人近年类似业绩`
3. **保持条款名称完整**：不要简化或修改条款名称
4. 在前面加上"分数第几名"
5. 完整变量名：`分数第一名投标人近年类似业绩`

**其他要求：**
6. 只提取返回的候选人名称对应的得分，忽略其他投标人
7. 变量名不要包含多余的文字
8. **再次强调：必须去除分值范围【X~X】，但保持条款名称完整**

请按照以下JSON格式返回结果：
```json
{{
  "candidate_names": [
    "第一名候选人完整名称",
    "第二名候选人完整名称"
  ],
  "score_variables": [
    {{
      "variable_name": "分数第一名近年投标人类似项目业绩",
      "variable_value": "8.5",
      "reference_source": {{
        "source_url": "",
        "evidence_text": "从商务部分评分表中提取",
        "pages": "",
        "file_type": "evaluation_summary_file"
      }}
    }},
    {{
      "variable_name": "分数第一名三体系认证",
      "variable_value": "3.0",
      "reference_source": {{
        "source_url": "",
        "evidence_text": "从商务部分评分表中提取",
        "pages": "",
        "file_type": "evaluation_summary_file"
      }}
    }},
    {{
      "variable_name": "分数第二名业主反馈",
      "variable_value": "7.0",
      "reference_source": {{
        "source_url": "",
        "evidence_text": "从商务部分评分表中提取",
        "pages": "",
        "file_type": "evaluation_summary_file"
      }}
    }}
  ]
}}
```

**重要提示：**
- 只返回前{count}名候选人
- 如果表格中的候选人数量少于{count}，则返回实际数量
- 确保候选人名称的完整性和准确性
- **提取所有评标条款的得分，不要遗漏**
- **必须去除分值范围**（如【0~6】、【0~4】等），但保持条款名称完整
  - 正确：`分数第一名投标人近年类似业绩`（去除了【0~6】）
  - 错误：`分数第一名投标人近年类似业绩【0~6】`（包含了分值范围）
- **条款名称必须完整**：去除分值范围后，不能再简化条款名称
  - 正确：`投标人近年类似业绩【0~6】` → `分数第一名投标人近年类似业绩`
  - 错误：`投标人近年类似业绩【0~6】` → `分数第一名投标人业绩`（简化了）
- 如果条款名称中包含"三体系认证"，只保留"三体系认证"，去掉其他描述和分值范围
- 如果某个候选人的某个条款没有得分，则跳过该变量
- 只返回JSON格式，不要添加任何其他文字说明
"""
    return prompt

