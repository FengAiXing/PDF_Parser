"""
资格评审标准人员信息提取提示词生成器
用于从人员配备组成表中提取指定职位的人员信息
"""

from typing import List


def build_qualification_personnel_extraction_prompt(
    clause_name: str,
    positions: List[str],
    ranking: str
) -> str:
    """
    构建资格评审标准人员信息提取的提示词
    
    Args:
        clause_name: 条款名称
        positions: 职位名称列表
        ranking: 排名信息
        
    Returns:
        str: 构建的提示词
    """
    positions_text = "、".join(positions)
    if len(positions) > 1:
        positions_desc = f"以下职位之一：{positions_text}（如果一个人兼任多个职位，需要同时匹配）"
    else:
        positions_desc = f"职位：{positions_text}"
    
    prompt = f"""你是一个专业的招投标文件分析专家。请从人员配备组成表中提取指定职位的人员信息。

## 任务说明

根据资格评审标准条款"{clause_name}"，从人员配备组成表中提取对应职位的人员信息。

**需要匹配的职位：** {positions_desc}

## 核心提取要求

### 1. 职位匹配规则（非常重要）

#### 完全匹配规则：
- **如果条款是"设计负责人"，职务必须是"设计负责人"，不能是"XX设计负责人"或"设计负责人XX"**
- **如果条款是"项目经理"，职务必须是"项目经理"，不能是"XX项目经理"或"项目经理XX"**
- **必须完全匹配，不能部分匹配**

#### 兼任职位处理：
- **如果条款是"项目经理兼设计负责人"，需要查找职务为"项目经理兼设计负责人"的人员**
- **或者查找职务为"项目经理"且同时兼任"设计负责人"的人员**
- **如果一个人兼任多个职位，需要同时匹配这些职位**

#### 匹配示例：
- 条款："设计负责人" → 匹配职务："设计负责人" ✅
- 条款："设计负责人" → 不匹配职务："工艺设计负责人" ❌
- 条款："设计负责人" → 不匹配职务："设计负责人助理" ❌
- 条款："项目经理兼设计负责人" → 匹配职务："项目经理兼设计负责人" ✅
- 条款："项目经理兼设计负责人" → 匹配职务："项目经理"（如果该人员同时担任设计负责人）✅

### 2. 提取信息格式

对于每个匹配的职位，需要提取以下信息，并按照顺序用换行符`\n`分隔：

**格式（单个证书）：**
```
姓名
证书名称
证书编号
```

**格式（多个证书）：**
```
姓名
证书名称：XXX
证书编号：XXX
证书名称：XXX
证书编号：XXX
...
```

**示例（多个证书）：**
```
姓名：张三
证书名称：注册化工工程师
证书编号：F0002911
证书名称：职称证
证书编号：I01239947
```

### 3. 人员配备组成表分析

- 仔细分析人员配备组成表（附件1: 项目管理机构组成表）
- 查找"拟任职务"列，找到完全匹配的职位
- 提取对应行的以下信息：
  - **姓名**：从"姓名"列提取
  - **证书名称**：从"执业或职业资格证明"中的"证书名称"提取（多个证书用换行符"\n"分隔，每个证书名称占一行）
  - **证书编号**：从"执业或职业资格证明"中的"证号"提取（多个证书用换行符"\n"分隔，每个证书编号占一行）

### 4. 变量名格式要求

- **变量名格式："{ranking}{clause_name}"（只返回一个变量）**
- 例如：条款是"设计负责人" → 变量名："{ranking}设计负责人"
- **变量值格式：姓名：XXX\\n证书名称：XXX\\n证书编号：XXX\\n证书名称：XXX\\n证书编号：XXX...（所有信息用换行符分隔）**
- **必须包含排名信息（{ranking}）和完整的条款名称**

## 输出格式

请按照以下JSON数组格式输出提取结果（每个条款只返回一个变量）：

```json
[
  {{
    "variable_name": "{ranking}{clause_name}",
    "variable_value": "姓名：XXX\\n证书名称：XXX\\n证书编号：XXX\\n证书名称：XXX\\n证书编号：XXX",
    "reference_source": {{
      "source_url": "",
      "evidence_text": "人员配备组成表",
      "pages": "",
      "file_type": "candidate_bid_file"
    }}
  }}
]
```

**变量值格式说明：**
- 第一行：姓名
- 第二行：第一个证书名称
- 第三行：第一个证书编号
- 第四行：第二个证书名称（如果有）
- 第五行：第二个证书编号（如果有）
- ...以此类推

**示例（一个人有2个证书）：**
```json
[
  {{
    "variable_name": "第一名设计负责人",
    "variable_value": "姓名：张三\\n证书名称：注册化工工程师\\n证书编号：F0002911\\n证书名称：职称证\\n证书编号：I01239947",
    "reference_source": {{
      "source_url": "",
      "evidence_text": "人员配备组成表",
      "pages": "",
      "file_type": "candidate_bid_file"
    }}
  }}
]
```

## 输出要求

1. **必须严格按照职位完全匹配规则**
2. **如果找不到匹配的职位，返回空数组**
3. **每个条款只返回一个变量，变量名为"{ranking}{clause_name}"**
4. **变量值格式：姓名：XXX\\n证书名称：XXX\\n证书编号：XXX\\n证书名称：XXX\\n证书编号：XXX...（所有信息按顺序用换行符分隔）**
5. **如果一个人有多个证书，按"证书名称+证书编号"的顺序依次列出**
6. **确保变量名包含完整的条款名称和排名信息**
7. **只提取匹配的职位，不要提取其他职位**

## 注意事项

1. **职位匹配必须完全匹配，不能部分匹配**
2. **如果条款中包含多个职位（用"兼"连接），需要查找同时匹配这些职位的人员**
3. **仔细分析人员配备组成表，确保找到正确的职位和人员**
4. **提取证书信息时，确保证书名称和证书编号一一对应**
5. **如果一个人有多个证书，按顺序列出所有证书**
6. **变量值中的换行符使用\\n表示，不要使用实际的换行符**

请开始分析以下投标文件的内容，提取相关信息：

## 文件内容：
$content

请严格按照上述文件内容进行信息提取，不得编造或使用其他文档的信息。"""

    return prompt

