"""
商务部分通用条款提取提示词生成器
用于生成商务部分评分表中通用条款信息的AI提取提示词
"""

from typing import Dict, List, Any
from .prompt_utils import get_rank_name


def generate_business_general_prompt(
    candidate_count: int,
    clauses: List[str],
    candidate_names: Dict[int, str] = None,
    other_requirements: str = ""
) -> str:
    """生成通用条款提取提示词"""
    
    # 生成候选人名称说明
    candidate_names_text = ""
    if candidate_names:
        candidate_names_text = "\n**各候选人名称：**\n"
        for rank, name in candidate_names.items():
            rank_name = get_rank_name(rank)
            candidate_names_text += f"- {rank_name}：{name}\n"
    
    # 格式化条款
    clauses_text = "、".join(clauses)
    
    prompt = f"""## 一、角色定义
你是一位经验丰富的评标专家，负责从商务部分评分表中提取和分析候选人投标文件中的各类信息。

## 二、任务说明
请仔细分析以下候选人投标文件内容，根据【商务评分标准】中的条款，准确提取各条款要求的内容。
所有信息必须严格依据文件内容，不得自行编造或补充未提及内容。

## 三、文件类型特定指导
当前处理的文件类型：**candidate_bid_files（候选人投标文件）**

本次招标项目共有 {candidate_count} 名中标候选人。
{candidate_names_text}

## 四、商务评分标准

**⚠️⚠️⚠️ 极其重要：以下是需要提取的全部条款列表（已排除业绩条款）**

**商务评分标准：**
{clauses_text}

**说明：**
- 以上条款用顿号（、）分隔
- 这些是从商务部分评分表中提取的纯粹条款名称
- **所有业绩相关的条款已经被排除**，不在此列表中

**其他条款要求（作为判断依据）：**
{other_requirements if other_requirements else "未提供"}

**⚠️⚠️⚠️ 核心提取要求（必须严格遵守）：**
1. **仅提取条款列表中的内容**：
   - 只提取上面用顿号分隔的条款中明确要求的内容
   - 每个条款都要对应一个变量进行提取
   
2. **条款中没有的绝对不要提取**：
   - ❌ 如果条款列表中没有"业绩"，就不要提取业绩信息
   - ❌ 如果条款列表中没有"业主反馈"，就不要提取业主反馈信息
   - ❌ 如果条款列表中没有"综合实力"，就不要提取综合实力信息
   - ✅ 只提取条款列表中明确列出的条款
   
3. **每个条款都要处理**：
   - 条款列表中的每个条款都要在投标文件中查找
   
4. **区分不同候选人**：
   - 确保每个候选人的信息从该候选人对应的投标文件中提取
   

## 五、提取规则

1. **准确性原则**
   - 所有信息必须来自原文，不得编造
   - 如实提取，保持原文表述
   - 如果信息不完整，请如实提取已有部分

2. **完整性原则**
   - 每个条款都要提取
   - 不要遗漏任何一个条款

3. **区分原则**
   - 请明确区分每个候选人的信息
   - 确保不要混淆不同候选人的信息

4. **条款对应原则**
   - 根据商务评分标准的要求进行提取或评价
   - 条款中要求什么内容，就提取什么内容

## 六、常见条款提取说明（仅供参考）

**⚠️ 重要提醒：以下提取规则仅在条款列表中有对应条款时才使用**

### 6.1 其他岗位主要人员配备情况
**提取规则：**
1. 从其他条款要求中判断对其他岗位主要人员配备情况要求是什么
2. 从投标文件第二部分 商务部分 第七章资格审查资料中查找其他岗位主要人员配备情况
3. 提取负责人名称和负责人等级，以及配置担任职务

**提取格式：**
```
xxxx负责人：获取负责人职称
岗位名称：XXX
```

### 6.2 项目组成员技术能力
**提取规则：**
1. 从其他条款要求中判断对项目组成员技术能力的要求是什么
2. 从投标文件第二部分 商务部分 第七章资格审查资料中查找项目组成员技术能力

**提取格式：**
```
XX人
```

### 6.3 综合实力
**提取规则：**
1. 从其他条款要求中判断对综合实力的评审因素
2. 从投标文件第二部分 商务部分 第七章资格审查资料中查找综合实力的内容
3. **需要全面提取以下方面的信息：**
   - **证书**：各类资质证书、认证证书、荣誉证书等（证书名称、颁发日期）
   - **规模**：企业规模、注册资本、员工数量、业务规模等
   - **商业信誉**：银行资信等级、纳税信用等级、信用评级等
   - **管理**：管理体系认证、管理能力、组织架构等
   - **其他**：企业实力、技术能力、市场地位等相关信息

**提取要求：**
- 如果内容较多，需要**精简概括**，提取**核心要点**
- 不要照搬原文，要**概括主要内容**
- 按照重要性排序，优先提取关键信息
- 如果文本较长，控制在合理长度内，突出主要亮点

**提取格式：**
```
证书：XXX（证书名称，如有多个证书用分号分隔）
规模：XXX（企业规模、注册资本、员工数量等关键信息）
商业信誉：XXX（银行资信、纳税信用、信用评级等）
管理：XXX（管理体系、管理能力等）
其他：XXX（其他重要综合实力信息）
```

**精简示例：**
- 如果原文很长，提取关键信息并概括，例如：
  - 原文："公司拥有ISO9001质量管理体系认证、ISO14001环境管理体系认证、OHSAS18001职业健康安全管理体系认证，注册资本5000万元，员工500人，银行资信AAA级..."
  - 提取结果："证书：ISO9001、ISO14001、OHSAS18001认证；规模：注册资本5000万元，员工500人；商业信誉：银行资信AAA级"

如果无相关信息，则用一句话总结概括企业的综合实力

### 6.4 银行资信
**提取规则：**
从其他条款要求中判断银行资信要求

**提取格式：**
```
银行资信等级：XXX
```

### 6.5 投标人纳税信用等级
**提取规则：**
1. 从其他条款要求中判断对投标人纳税信用等级的评审因素
2. 从投标文件第二部分 商务部分 第七章资格审查资料中查找投标人纳税评价信息
3. 提取评价信息表头以及评价等级

### 6.6 业主反馈
**提取格式：**
```
反馈单名称：XXX\n反馈单位：XXX\n反馈时间：XXXX年XX月XX日
```

### 6.7 企业获奖情况
**提取规则：**
1. 从其他条款要求中判断对综合实力的评审因素
2. 查找综合实力的内容

**提取格式：**
```
获奖日期：XXXX年XX月XX日\n获奖证书：XXX
```
如果无证书则用一句话总结概括企业的综合实力

### 6.8 大项目交付能力
**提取规则：**
查找综合实力中与大项目交付能力相关的条款内容

**提取格式：**
```
合同名称：XXX（提取合同、中标通知书或协议书上的项目名称）
合同容量：XXX（有则获取没有则不显示）
甲方名称：XXX（从业绩合同表中获取委托人或甲方的名称）
合同签订日期：XXXX年XX月XX日
开票日期：XXXX年XX月XX日
```

### 6.9 联合体投标人
**提取规则：**
1. 从投标文件中判断投标人是否为联合体投标人
2. 如果是联合体投标人，提取牵头人和所有成员信息
3. 如果是非联合体投标人，直接返回"非联合体投标人"

**提取格式：**
- **联合体投标人格式**：
```
牵头人：XXX
成员一：XXX
成员二：XXX
```
（如果有更多成员，继续添加"成员三："、"成员四："等）

- **非联合体投标人格式**：
```
非联合体投标人
```

**注意事项：**
- 必须准确判断投标人类型（联合体或非联合体）
- 如果是联合体，必须提取牵头人和所有成员，不要遗漏
- 成员按照"成员一"、"成员二"、"成员三"的顺序编号
- 每个成员信息单独一行，使用换行符（\n）分隔

### 6.10 其他条款
- **财务状况**：提取财务报表相关数据、资产负债情况等
- **技术能力**：提取技术力量、创新能力、专利技术等信息
- **质量管理**：提取质量管理体系认证、质量保证措施等信息
- **售后服务**：提取服务承诺、服务网络、响应时间等信息

**⚠️⚠️⚠️ 再次强调：只提取条款列表中明确要求的内容，条款中没有的不要提取,并且正确添加换行符\n**

## 七、输出格式

请严格按照JSON数组格式输出，每个变量是一个独立的对象：

```json
[
   {{
    "variable_name": "第一名XXX",
    "variable_value": "具体信息内容",
    "reference_source": {{
      "source_url": "文件URL",
      "evidence_text": "XXX部分 ...相关内容预览...",
      "pages": "1, 2, 3",
      "file_type": "candidate_bid_files"
    }}
  }},
  {{
    "variable_name": "第二名XXX",
    "variable_value": "具体信息内容",
    "reference_source": {{
      "source_url": "文件URL",
      "evidence_text": "XXX部分 ...相关内容预览...",
      "pages": "1, 2",
      "file_type": "candidate_bid_files"
    }}
  }},
  ...
]
```

**字段说明：**
- `variable_name`: 变量名称（格式：第X名+条款名称，不再使用"三"前缀）
- `variable_value`: 提取的变量值
- `reference_source`: 引用来源信息
  - `source_url`: 文件URL地址
  - `evidence_text`: 证据文本（包含章节和内容预览，50-100字）
  - `pages`: 信息所在页码（多个页码用英文逗号分隔，如 "1, 2, 3"）
  - `file_type`: 固定为 "candidate_bid_files"

**⚠️ 变量名格式规则：**
1. **基本格式**：第X名 + 条款名称（不再使用"三"前缀）
2. **条款名称**：使用商务部分评分表中的条款名称（完整不简化）
   - 如果条款是"业主反馈" → 变量名：第一名业主反馈、第二名业主反馈...
   - 如果条款是"综合实力" → 变量名：第一名综合实力、第二名综合实力...
   - 如果条款是"社会信誉" → 变量名：第一名社会信誉、第二名社会信誉...
3. **不要添加序号**：通用条款不需要序号（与业绩不同）

**示例：**
- 条款"业主反馈"：第一名业主反馈、第二名业主反馈...
- 条款"综合实力"：第一名综合实力、第二名综合实力...
- 条款"售后服务"：第一名售后服务、第二名售后服务...

**注意事项：**
- **⚠️ 最重要**：严格按照条款列表提取，条款中没有的内容不要提取
- 信息较多时，用分号（；）分隔各项内容
- 确保JSON格式正确，必须是数组格式
- **变量名必须与候选人排名对应**：第一名的信息从第一名的投标文件中提取
- **变量名必须包含完整的条款名称**：不要简化或修改条款名称

请开始分析以下投标文件的内容，并提取相关信息：

## 文件内容：
$content
请严格按照上述文件内容进行信息提取，不得编造或使用其他文档的信息。
"""
    
    return prompt

